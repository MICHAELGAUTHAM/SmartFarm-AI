// Current language state
let currentLang = localStorage.getItem('sf_lang') || 'en';

export function getLang() { return currentLang; }

export function t(key) {
  return translations[currentLang][key] || translations['en'][key] || key;
}

export function setLang(lang) {
  currentLang = lang;
  localStorage.setItem('sf_lang', lang);
  applyTranslations();
}

export function toggleLang() {
  setLang(currentLang === 'en' ? 'ta' : 'en');
}

// Apply all data-i18n attributes
export function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const attr = el.getAttribute('data-i18n-attr');
    if (attr) {
      el.setAttribute(attr, t(key));
    } else {
      el.textContent = t(key);
    }
  });

  // Update lang toggle button
  const btn = document.getElementById('langToggleBtn');
  if (btn) btn.textContent = t('lang_toggle');

  // Update html lang attribute
  document.documentElement.lang = currentLang === 'ta' ? 'ta' : 'en';

  // Update search placeholder
  const searchInput = document.getElementById('cropSearch');
  if (searchInput) searchInput.placeholder = t('crop_search_placeholder');

  // Dispatch event so app.js can re-render dynamic content
  document.dispatchEvent(new CustomEvent('langchange', { detail: currentLang }));
}
